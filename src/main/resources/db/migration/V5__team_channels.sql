ALTER TABLE team_workspace ADD COLUMN channels_initialised BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE team_channel (
    id UUID PRIMARY KEY,
    workspace_id UUID NOT NULL REFERENCES team_workspace(id),
    name VARCHAR(80) NOT NULL,
    description VARCHAR(500) NOT NULL DEFAULT '',
    category VARCHAR(80) NOT NULL DEFAULT 'Team',
    audience VARCHAR(20) NOT NULL DEFAULT 'TEAM' CHECK (audience IN ('TEAM', 'SUPPORT', 'MODERATION', 'ADMIN')),
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (workspace_id, name)
);
CREATE TABLE team_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id UUID NOT NULL REFERENCES team_channel(id),
    author_owner_id UUID REFERENCES admin_account(id),
    author_team_id UUID REFERENCES team_account(id),
    body VARCHAR(4000) NOT NULL,
    version INTEGER NOT NULL DEFAULT 0,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    edited_at TIMESTAMP WITH TIME ZONE,
    CHECK ((author_owner_id IS NULL) <> (author_team_id IS NULL))
);
CREATE INDEX team_message_channel_time ON team_message(channel_id, id);
